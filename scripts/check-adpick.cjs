const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = ts.transpileModule(fs.readFileSync('services/adpick.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
let requested;
const context = { exports: {}, URL, URLSearchParams, process: { env: { EXPO_PUBLIC_ADPICK_AFFILIATE_ID: 'test-affiliate' } }, fetch: async url => { requested = new URL(url); return { ok: true, json: async () => [] }; } };
vm.runInNewContext(source, context);
const { parseAdpickAds, fetchAdpickAds } = context.exports;
const fixture = { apOffer: 'abc', apAppTitle: '광고', apHeadline: '설명', apAppPromoText: '설명', apOS: 'Both', apImages: { icon256: 'https://example.com/icon.png' }, apTrackingLink: 'https://example.com/click' };
const [icon] = parseAdpickAds([fixture]);
assert.equal(icon.id, 'abc');
assert.equal(icon.imageKind, 'icon');
assert.equal(icon.description, '설명');
assert.equal(icon.category, 'Android · iOS');
const [banner] = parseAdpickAds([{ ...fixture, apImages: { ...fixture.apImages, banner1024x500: 'https://example.com/banner.png' } }]);
assert.equal(banner.imageKind, 'banner');
assert.equal(banner.imageUrl, 'https://example.com/banner.png');
assert.equal(parseAdpickAds([]).length, 0);
assert.equal(parseAdpickAds([null, {}, { apOffer: 1 }]).length, 0);
assert.throws(() => parseAdpickAds({ error: 'provider error' }));
const [unsafe] = parseAdpickAds([{ ...fixture, apImages: {}, apTrackingLink: 'javascript:alert(1)' }]);
assert.equal(unsafe.imageUrl, null);
assert.equal(unsafe.link, null);
(async () => {
  await fetchAdpickAds(new AbortController().signal);
  assert.equal(requested.protocol, 'https:');
  assert.equal(requested.searchParams.get('affid'), 'test-affiliate');
  assert.equal(requested.searchParams.get('order'), 'rand');
  context.process.env.EXPO_PUBLIC_ADPICK_AFFILIATE_ID = '';
  await assert.rejects(() => fetchAdpickAds(new AbortController().signal));
  console.log('PASS: Adpick array response, banner/icon priority, malformed/error/empty responses, URL validation and affiliate query.');
})().catch(error => { console.error(error); process.exitCode = 1; });
