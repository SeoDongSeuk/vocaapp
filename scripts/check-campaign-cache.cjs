const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const counts = { tenping: 0, adpick: 0, shopping: 0, recommendations: 0 };
let fail = false;
const loader = provider => async () => {
  counts[provider]++;
  if (fail) throw new Error('temporary failure');
  return [{ id: provider + counts[provider], title: 'fixture', description: '', category: '', imageUrl: null, link: null }];
};
const modules = { './tenping': { fetchTenpingAds: loader('tenping') }, './adpick': { fetchAdpickAds: loader('adpick') }, './shopping': { fetchShoppingDeals: loader('shopping'), fetchShoppingRecommendations: loader('recommendations') } };
const source = ts.transpileModule(fs.readFileSync('services/campaignCache.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const context = { exports: {}, require: name => modules[name], AbortController, setTimeout, clearTimeout };
vm.runInNewContext(source, context);
const { refreshCampaignOnEntry: enter, getCampaignSnapshot: snapshot, CAMPAIGN_REFRESH_MS: interval } = context.exports;
(async () => {
  assert.equal(interval, 180000);
  assert.equal(snapshot('shopping').status, 'idle');
  assert.equal(counts.shopping, 0);
  const first = enter('shopping', 1000);
  assert.equal(enter('shopping', 1001), first, 'Concurrent entries share one request');
  await first;
  assert.equal(counts.shopping, 1);
  await enter('shopping', 180999);
  assert.equal(counts.shopping, 1, 'No refresh before three minutes');
  await enter('shopping', 181000);
  assert.equal(counts.shopping, 2, 'Refresh at three-minute boundary on entry');
  await enter('recommendations', 181001);
  assert.equal(counts.recommendations, 1, 'Independent provider cache');
  assert.equal(counts.shopping, 2);
  fail = true;
  const failed = await enter('shopping', 361000);
  assert.equal(failed.status, 'error');
  assert.equal(failed.ads[0].id, 'shopping2', 'Keep previous data on error');
  assert.equal(counts.shopping, 3);
  await enter('shopping', 361001);
  assert.equal(counts.shopping, 3, 'Failed requests are throttled too');
  fail = false;
  await enter('shopping', 541000);
  assert.equal(snapshot('shopping').status, 'ready');
  assert.equal(counts.shopping, 4);
  console.log('PASS: lazy loading, shared in-flight request, per-provider 180-second gate, boundary refresh, failure throttling and cached data retention.');
})().catch(error => { console.error(error); process.exitCode = 1; });
