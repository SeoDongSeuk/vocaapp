const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = ts.transpileModule(fs.readFileSync('services/shopping.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
let requested;
const context = { exports: {}, URL, URLSearchParams, process: { env: { EXPO_PUBLIC_ADPICK_AFFILIATE_ID: 'test-affiliate' } }, fetch: async url => { requested = new URL(url); return { ok: true, json: async () => [{ list: [] }] }; } };
vm.runInNewContext(source, context);
const { parseShoppingDeals, fetchShoppingDeals, fetchShoppingRecommendations } = context.exports;
const product = { product_name: '테스트 상품', photo: 'https://example.com/photo.jpg', mall_name: '테스트몰', price_sale: '1,100,000', price_org: '1,850,000', commission: '10%', buyurl: 'https://example.com/buy' };
const [deal] = parseShoppingDeals([{ title: '핫딜', list: [product] }]);
assert.equal(deal.salePrice, 1100000);
assert.equal(deal.originalPrice, 1850000);
assert.equal(deal.category, '테스트몰');
assert.equal(deal.imageKind, 'product');
assert.equal('commission' in deal, false);
assert.equal(parseShoppingDeals([{ list: [product, product] }]).length, 1);
assert.equal(parseShoppingDeals([{ list: [product] }, { list: [{ ...product, buyurl: 'https://example.com/other' }] }]).length, 2);
assert.equal(parseShoppingDeals([]).length, 0);
assert.equal(parseShoppingDeals([{ list: [] }]).length, 0);
assert.throws(() => parseShoppingDeals({ error: 'provider error' }));
assert.throws(() => parseShoppingDeals([{ title: 'missing list' }]));
const [invalid] = parseShoppingDeals([{ list: [null, {}, { ...product, price_sale: '가격 문의', price_org: '', buyurl: 'javascript:alert(1)', photo: 'data:bad' }] }]);
assert.equal(invalid.salePrice, null);
assert.equal(invalid.originalPrice, null);
assert.equal(invalid.link, null);
assert.equal(invalid.imageUrl, null);
assert.equal(parseShoppingDeals([{ list: [{ ...product, price_sale: 0 }] }])[0].salePrice, 0);
(async () => {
  await fetchShoppingDeals(new AbortController().signal);
  assert.equal(requested.protocol, 'https:');
  assert.equal(requested.searchParams.get('affid'), 'test-affiliate');
  assert.equal(requested.pathname, '/apis/sdk_shopping_hotdeal.php');
  await fetchShoppingRecommendations(new AbortController().signal);
  assert.equal(requested.pathname, '/apis/sdk_shopping.php');
  context.process.env.EXPO_PUBLIC_ADPICK_AFFILIATE_ID = '';
  await assert.rejects(() => fetchShoppingDeals(new AbortController().signal));
  console.log('PASS: nested shopping groups, prices, missing values, duplicates, URL validation, empty/error responses and affiliate configuration.');
})().catch(error => { console.error(error); process.exitCode = 1; });
