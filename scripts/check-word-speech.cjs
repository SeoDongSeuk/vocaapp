const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
let stops = 0;
let voices = [ { identifier: 'ko', language: 'ko-KR' }, { identifier: 'gb', language: 'en-GB' }, { identifier: 'us', language: 'en-US' } ];
let lookup = async () => voices;
const utterances = [];
const speech = { stop: async () => { stops++; }, getAvailableVoicesAsync: () => lookup(), speak: (text, options) => utterances.push({ text, options }) };
const source = ts.transpileModule(fs.readFileSync('services/wordSpeech.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const context = { exports: {}, require: name => { assert.equal(name, 'expo-speech'); return speech; }, setTimeout, clearTimeout };
vm.runInNewContext(source, context);
const { speakWord, stopWordSpeech } = context.exports;
let starts = 0, finishes = 0, errors = 0;
const callbacks = { onStart: () => starts++, onDone: () => finishes++, onError: () => errors++ };
(async () => {
  await speakWord(' apple ', callbacks);
  assert.equal(utterances[0].text, 'apple');
  assert.equal(utterances[0].options.voice, 'us');
  assert.equal(utterances[0].options.language, 'en-US');
  assert.equal(utterances[0].options.rate, 0.85);
  utterances[0].options.onStart();
  assert.equal(starts, 1);
  await stopWordSpeech();
  utterances[0].options.onDone();
  utterances[0].options.onError();
  assert.equal(finishes, 0, 'Ignore stale completion after stopping');
  assert.equal(errors, 0);
  const before = utterances.length;
  let resolveVoices;
  lookup = () => new Promise(resolve => { resolveVoices = resolve; });
  const pending = speakWord('late word', callbacks);
  await new Promise(resolve => setImmediate(resolve));
  await stopWordSpeech();
  resolveVoices(voices);
  await pending;
  assert.equal(utterances.length, before, 'Pending lookup cannot speak after leaving the word');
  lookup = async () => [{ identifier: 'uk', language: 'en_GB' }];
  await speakWord('banana', callbacks);
  assert.equal(utterances.at(-1).options.language, 'en-GB');
  assert.equal(utterances.at(-1).options.voice, 'uk');
  lookup = async () => [{ identifier: 'ko', language: 'ko-KR' }];
  await assert.rejects(() => speakWord('hello', callbacks), /영어 음성/);
  lookup = async () => [];
  await speakWord('orange', callbacks);
  assert.equal(utterances.at(-1).options.language, 'en-US');
  utterances.at(-1).options.onDone();
  assert.equal(finishes, 1);
  await speakWord(' ', callbacks);
  assert.ok(stops >= 5);
  console.log('PASS: English voice preference, normalized language, stop-before-play, pending lookup cancellation, stale callback suppression and missing voice handling.');
})().catch(error => { console.error(error); process.exitCode = 1; });
